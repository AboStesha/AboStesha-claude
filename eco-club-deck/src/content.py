AR = '٠١٢٣٤٥٦٧٨٩'
def ar(s):
    out = []
    for c in str(s):
        if c.isdigit(): out.append(AR[int(c)])
        elif c == ',': out.append('٬')
        elif c == '.': out.append('٫')
        else: out.append(c)
    return ''.join(out)

def n(x, d=0):
    return ar(f'{x:,.{d}f}')

def k(usd):
    """USD as Arabic 'ألف $' / 'مليون $'."""
    if usd >= 1e6:
        v = usd / 1e6
        return ar(f'{v:.2f}'.rstrip('0').rstrip('.')) + ' مليون $'
    return n(round(usd / 1000)) + ' ألف $'

def facts(items):
    return ''.join(f'<div><div class="k">{a}</div><div class="v">{b}</div></div>' for a, b in items)

def ticks(items):
    return ''.join(f'<li>{x}</li>' for x in items)

def chips(items):
    return ''.join(f'<div class="chipline">{x}</div>' for x in items)

def cards(items):
    return ''.join(f'<div class="card"><h3>{t}</h3><p>{p}</p></div>' for t, p in items)

def why(items):
    return ''.join(
        f'<div class="why-card" data-a data-d="{i + 2}"><div class="v">{v}</div><div class="l">{l}</div><div class="src">{s}</div></div>'
        for i, (v, l, s) in enumerate(items))

def kpis(items):
    return ''.join(f'<div class="kpi" style="--c:{c}"><div class="v">{v}</div><div class="l">{l}</div></div>' for v, l, c in items)

def progs(items):
    return ''.join(f'<div><h4>{t}</h4><p>{p}</p></div>' for t, p in items)

def slider(id_, label, mn, mx, step, val, money=False):
    m = ' data-money="1"' if money else ''
    return (f'<div class="sl"><label for="{id_}"><span>{label}</span><output for="{id_}"></output></label>'
            f'<input type="range" id="{id_}" min="{mn}" max="{mx}" step="{step}" value="{val}"{m}></div>')

